def peaks(path, bars=64):
    with wave.open(path) as w:
        ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    dtype = {1: np.int8, 2: np.int16, 4: np.int32}[sw]
    data = np.frombuffer(raw, dtype=dtype).astype(np.float32)
    if ch > 1:
        data = data.reshape(-1, ch).mean(axis=1)
    data /= max(1.0, float(np.abs(data).max()))
    # a gentle log-ish weighting keeps quiet syllables visible
    step = max(1, len(data) // bars)
    vals = []
    for i in range(bars):
        chunk = data[i * step:(i + 1) * step]
        rms = float(np.sqrt(np.mean(chunk ** 2))) if len(chunk) else 0.0
        vals.append(rms)
    # smooth the contour so the waveform reads as a phrase, not noise
    smooth = []
    for i, v in enumerate(vals):
        a = vals[i - 1] if i > 0 else v
        b = vals[i + 1] if i < len(vals) - 1 else v
        smooth.append(a * 0.22 + v * 0.56 + b * 0.22)
    top = max(smooth) or 1.0
    return [round(0.07 + 0.93 * ((v / top) ** 0.55), 3) for v in smooth]


def encode(src, name):
    dst = os.path.join(AUD, name + ".mp3")
    subprocess.run(
        [FFMPEG, "-y", "-loglevel", "error", "-i", src, "-ac", "1", "-ar", "24000",
         "-b:a", "80k", dst], check=True,
    )
    dur = subprocess.run(
        [FFPROBE, "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", dst], check=True, capture_output=True, text=True,
    ).stdout.strip()
    return {"file": name + ".mp3", "duration": round(float(dur), 2), "peaks": peaks(src)}


