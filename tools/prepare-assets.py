def plate(src, watermark, crop, name):
    im = Image.open(src).convert("RGB")
    d = ImageDraw.Draw(im)
    d.rectangle(watermark, fill=(255, 255, 255))  # remove generator watermark
    im = im.crop(crop)
    for h, suffix in ((1200, ""), (620, "-sm")):
        w = round(im.width * h / im.height)
        im.resize((w, h), Image.LANCZOS).save(
            os.path.join(IMG, f"{name}{suffix}.webp"), "WEBP", quality=92, method=6
        )
    print("plate", name, im.size)


